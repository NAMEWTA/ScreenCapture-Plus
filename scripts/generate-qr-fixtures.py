#!/usr/bin/env python3
"""Regenerate QR matrices with the exact, unmodified Segno 1.6.6 source.

No QR encoding algorithm lives here. Production and CI consume the checked-in
header; this optional maintainer tool verifies the upstream modules before
calling segno.make. See docs/qr-recognition.md for the pinned source and license.
"""

import argparse
import hashlib
import sys
from pathlib import Path


SEGNO_COMMIT = "9b67a3f2914be966c35dd8f00bef19d01b9ec68e"
SEGNO_FILES = {
    "__init__.py": "103b785a931454385e58c3f0887f5fe23919dc0b",
    "encoder.py": "29282fc906989d4940b1f8982df9a0bc1ee43867",
    "consts.py": "6025c56259f10383df2683fd817686ccb4e67fdb",
    "utils.py": "3c4e21c62d7252e1c62a039f4251c785abc4a053",
    "writers.py": "5d43c8cc123093af9162b5b2537bf09337705594",
}


def git_blob_sha(content):
    return hashlib.sha1(b"blob " + str(len(content)).encode("ascii") + b"\0" + content).hexdigest()


def utf16_literal(text):
    units = len(text.encode("utf-16-le")) // 2
    quoted = []
    for char in text:
        value = ord(char)
        if char in ('"', "\\"):
            quoted.append("\\" + char)
        elif 32 <= value <= 126:
            quoted.append(char)
        elif value == 0:
            quoted.append("\\0")
        elif value < 0x10000:
            quoted.append(f"\\u{value:04x}")
        else:
            quoted.append(f"\\U{value:08x}")
    return 'std::u16string_view{u"' + "".join(quoted) + '", ' + str(units) + "}"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--segno-source", required=True, type=Path,
                        help="directory containing the segno/ package at the pinned commit")
    parser.add_argument("--output", type=Path,
                        default=Path(__file__).resolve().parents[1] / "tests/fixtures/qr/qr-fixtures.h")
    args = parser.parse_args()
    source = args.segno_source.resolve()
    for path, expected in SEGNO_FILES.items():
        actual = git_blob_sha((source / "segno" / path).read_bytes())
        if actual != expected:
            raise SystemExit(f"Segno {path}: expected pinned git blob {expected}, got {actual}")
    sys.path.insert(0, str(source))
    import segno
    if Path(segno.__file__).resolve() != source / "segno/__init__.py" or segno.__version__ != "1.6.6":
        raise SystemExit("The imported Segno is not the verified source")

    # name, raw bytes, mode, encoding, ECI, expected quirc type/ECI, expected
    # portable text, version. Empty expected text means an encoding boundary,
    # not that the raw payload is discarded. Windows ACP is tested against its
    # actual MultiByteToWideChar result separately.
    cases = [
        ("ascii", b"https://example.org/huhucapture", "byte", "ascii", False, 4, 0,
         "https://example.org/huhucapture", None),
        ("utf8", "截图 中文🙂".encode("utf-8"), "byte", "utf-8", False, 4, 0, "截图 中文🙂", None),
        ("kanji", "日本語".encode("shift_jis"), "kanji", "shift_jis", False, 8, 0, "日本語", None),
        ("cp932_wave_dash", bytes.fromhex("8160"), "kanji", "shift_jis", False, 8, 0, "～", None),
        ("eci_utf8", "完整备注🙂".encode("utf-8"), "byte", "utf-8", True, 4, 26, "完整备注🙂", None),
        ("eci_shift_jis", "日本語".encode("shift_jis"), "byte", "shift_jis", True, 4, 20, "日本語", None),
        ("eci_latin15", b"caf\xe9", "byte", "iso-8859-15", True, 4, 17, "café", None),
        ("legacy_unknown", b"\xff\xe9\x81", "byte", "iso-8859-1", False, 4, 0, "", None),
        ("eci_unsupported", bytes.fromhex("feff732b"), "byte", "utf-16-be", True, 4, 25, "", None),
        ("nul", b"one\0two", "byte", "ascii", False, 4, 0, "one\0two", None),
        ("empty", b"", "byte", "ascii", False, 4, 0, "", None),
        ("numeric", b"01234567890123456789", "numeric", "ascii", False, 1, 0, "01234567890123456789", None),
        ("alpha", b"HUHUCAPTURE 2026", "alphanumeric", "ascii", False, 2, 0, "HUHUCAPTURE 2026", None),
        ("version40", b"huhucapture: full-size grid, existing 65534-region detector", "byte", "ascii", False, 4, 0,
         "huhucapture: full-size grid, existing 65534-region detector", 40),
    ]
    lines = [
        "// Generated by scripts/generate-qr-fixtures.py; do not hand-edit matrices.",
        f"// Segno 1.6.6 ({SEGNO_COMMIT}), Lars Heuer, BSD-3-Clause.",
        "// No Segno runtime is linked or shipped; these are deterministic test data.",
        "#pragma once", "#include <array>", "#include <string_view>", "",
        "namespace HuhuCapture::TestQrFixtures {",
        "struct Fixture {",
        "    std::string_view name; int size; std::string_view modules, payload;",
        "    int dataType; unsigned eci; std::u16string_view text;",
        "};",
        f"inline constexpr std::array<Fixture, {len(cases)}> fixtures{{{{",
    ]
    for name, raw, mode, encoding, eci, data_type, expected_eci, text, version in cases:
        qr = segno.make(raw, mode=mode, encoding=encoding, eci=eci, version=version,
                        error="H", mask=2, boost_error=False, micro=False)
        lines.append(f'    {{"{name}", {len(qr.matrix)},')
        lines.extend('        "' + "".join(str(cell) for cell in row) + '"' for row in qr.matrix)
        payload = "".join(f"\\x{byte:02x}" for byte in raw)
        lines.append(f'        , std::string_view{{"{payload}", {len(raw)}}}, {data_type}, {expected_eci}, {utf16_literal(text)}}},')
    lines.extend(["}};", "} // namespace HuhuCapture::TestQrFixtures", ""])
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(f"Wrote {len(cases)} real QR matrices to {args.output}")


if __name__ == "__main__":
    main()
