#!/usr/bin/env python3
"""Render huhucapture brand assets from editable SVG source files.

Requires Python 3.10+, Pillow and the Inkscape command-line executable.
These are design-time tools only; the Windows build uses the checked-in ICO.
"""

from __future__ import annotations

import argparse
import copy
import shutil
import subprocess
import sys
import tempfile
import xml.etree.ElementTree as ET
from pathlib import Path

try:
    from PIL import Image
except ImportError as error:
    raise SystemExit("Install Pillow before running this script: python -m pip install Pillow") from error


ROOT = Path(__file__).resolve().parents[1]
BRAND = ROOT / "assets" / "brand"
SVG_NS = "http://www.w3.org/2000/svg"
ET.register_namespace("", SVG_NS)
ICON_SIZES = (16, 24, 32, 48, 64, 128, 256, 512, 1024)
ICO_SIZES = tuple(size for size in ICON_SIZES if size <= 256)
INK = "#67381F"
CREAM = "#FFF2DE"


def element(tag: str, attributes: dict[str, str] | None = None) -> ET.Element:
    return ET.Element(f"{{{SVG_NS}}}{tag}", attributes or {})


def svg_root(width: int, height: int, title: str, description: str) -> ET.Element:
    root = element("svg", {
        "width": str(width), "height": str(height), "viewBox": f"0 0 {width} {height}",
        "role": "img", "aria-labelledby": "title desc",
    })
    ET.SubElement(root, f"{{{SVG_NS}}}title", {"id": "title"}).text = title
    ET.SubElement(root, f"{{{SVG_NS}}}desc", {"id": "desc"}).text = description
    root.append(ET.Comment("Generated by scripts/generate-brand.py. Edit the mark / wordmark source SVGs."))
    return root


def artwork(source: ET.Element) -> list[ET.Element]:
    return [copy.deepcopy(child) for child in source
            if child.tag not in {f"{{{SVG_NS}}}title", f"{{{SVG_NS}}}desc"}]


def icon_from(mark: ET.Element, small: bool = False) -> ET.Element:
    description = "An orange tabby inside four capture corners on a warm cream tile."
    if small:
        description += " Simplified geometry for 16 to 48 pixel Windows icons."
    icon = svg_root(512, 512, "huhucapture", description)
    icon.append(element("rect", {
        "id": "icon-tile", "x": "8", "y": "8", "width": "496", "height": "496",
        "rx": "112", "fill": CREAM,
    }))
    icon.extend(artwork(mark))
    return icon


def logo_from(icon: ET.Element, wordmark: ET.Element, dark: bool) -> ET.Element:
    logo = svg_root(1040, 256, "huhucapture", "Orange tabby capture icon with the lowercase huhucapture wordmark.")
    icon_group = element("g", {"transform": "scale(.5)"})
    icon_group.extend(artwork(icon))
    logo.append(icon_group)
    wordmark_group = element("g", {"transform": "translate(288 60)"})
    wordmark_group.extend(artwork(wordmark))
    if dark:
        for part in wordmark_group.iter():
            if part.get("stroke") == INK:
                part.set("stroke", CREAM)
    logo.append(wordmark_group)
    return logo


def save_svg(path: Path, root: ET.Element) -> None:
    ET.indent(root, space="  ")
    # Keep the SVG compact enough to review, without host-specific metadata.
    path.write_text(ET.tostring(root, encoding="unicode") + "\n", encoding="utf-8", newline="\n")


def render(inkscape: str, svg: Path, png: Path, width: int) -> None:
    command = [inkscape, str(svg), "--export-area-page", "--export-type=png",
               f"--export-width={width}", f"--export-filename={png}"]
    result = subprocess.run(command, text=True, capture_output=True, check=False)
    if result.returncode:
        raise RuntimeError(f"Inkscape failed rendering {svg.name}: {result.stderr.strip()}")
    # Normalize PNG storage: keep RGBA pixels, discard renderer timestamps and metadata.
    with Image.open(png) as rendered:
        rgba = rendered.convert("RGBA")
        normalized = Image.frombytes("RGBA", rgba.size, rgba.tobytes())
        normalized.save(png, format="PNG", optimize=False, compress_level=9)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--inkscape", default="inkscape", help="Inkscape CLI path (default: PATH)")
    args = parser.parse_args()
    inkscape = shutil.which(args.inkscape)
    if not inkscape:
        parser.error("Inkscape was not found; install it or pass --inkscape /path/to/inkscape")

    mark = ET.parse(BRAND / "huhucapture-mark.svg").getroot()
    small_mark = ET.parse(BRAND / "huhucapture-mark-small.svg").getroot()
    wordmark = ET.parse(BRAND / "huhucapture-wordmark.svg").getroot()
    icon = icon_from(mark)
    outputs = {
        "huhucapture-icon.svg": icon,
        "huhucapture-icon-small.svg": icon_from(small_mark, small=True),
        "huhucapture-logo-light.svg": logo_from(icon, wordmark, dark=False),
        "huhucapture-logo-dark.svg": logo_from(icon, wordmark, dark=True),
    }
    for name, root in outputs.items():
        save_svg(BRAND / name, root)

    # Render every size directly from its SVG, avoiding downscaling from a single PNG.
    with tempfile.TemporaryDirectory(prefix="huhucapture-brand-") as temporary:
        scratch = Path(temporary)
        for size in ICON_SIZES:
            source = BRAND / ("huhucapture-icon-small.svg" if size <= 48 else "huhucapture-icon.svg")
            png = scratch / f"huhucapture-icon-{size}.png"
            render(inkscape, source, png, size)
            shutil.copyfile(png, BRAND / png.name)

        frames: list[Image.Image] = []
        for size in ICO_SIZES:
            with Image.open(scratch / f"huhucapture-icon-{size}.png") as frame:
                frames.append(frame.convert("RGBA"))

        icon_path = ROOT / "resources" / "logo.ico"
        frames[-1].save(icon_path, format="ICO", append_images=frames[:-1],
                        sizes=[(size, size) for size in ICO_SIZES])
        # Fail immediately if a Pillow change ever omits or resizes an intended frame.
        with Image.open(icon_path) as saved:
            expected = {(size, size) for size in ICO_SIZES}
            if saved.ico.sizes() != expected:
                raise RuntimeError("Generated ICO does not contain all expected sizes")
            for frame in frames:
                if saved.ico.getimage(frame.size).convert("RGBA").tobytes() != frame.tobytes():
                    raise RuntimeError(f"Generated ICO frame differs from SVG render: {frame.size}")

        shutil.copyfile(scratch / "huhucapture-icon-512.png", ROOT / "docs" / "logo.png")

    print("Generated four SVG variants, nine PNG sizes, docs/logo.png and resources/logo.ico.")
    print("ICO frames: " + ", ".join(f"{size}x{size}" for size in ICO_SIZES))
    return 0


if __name__ == "__main__":
    try:
        sys.exit(main())
    except (OSError, RuntimeError, ET.ParseError) as error:
        print(f"Brand generation failed: {error}", file=sys.stderr)
        sys.exit(1)
