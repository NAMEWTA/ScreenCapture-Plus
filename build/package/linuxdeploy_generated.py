"""Reproduce the three non-binary outputs of the locked linuxdeploy generators."""
from __future__ import annotations

import hashlib
import json
from pathlib import Path
import re
import tarfile


LITERAL = r'"(?:[^"\\]|\\.)*"'
HOOK = 'linuxdeploy-plugin-qt-hook.sh'
OUTPUTS = ('appimage/AppRun', 'appimage/apprun-hooks/' + HOOK, 'appimage/usr/bin/qt.conf',
           'deb/opt/huhucapture/bin/qt.conf')
SOURCES = {'linuxdeploy': ('linuxdeploy', 'src/core/appdir_root_setup.cpp'),
           'linuxdeployPluginQt': ('linuxdeploy-plugin-qt', 'src/deployment.h')}


def source_text(archive, key, pin, api):
    expected = pin['sourceArchive']
    api.require(archive.stat().st_size == expected['size'] and api.digest(archive) == expected['sha256'],
                'Original linuxdeploy generator archive differs from the fixed source pin')
    repository, path = SOURCES[key]
    name = f"{repository}-{pin['commit']}/{path}"
    with tarfile.open(archive, 'r:gz') as source:
        matches = [item for item in source.getmembers() if item.name == name]
        api.require(len(matches) == 1 and matches[0].isfile() and 0 < matches[0].size < 1024 * 1024,
                    'Locked linuxdeploy generator source is missing or ambiguous')
        with source.extractfile(matches[0]) as stream:
            return stream.read().decode('utf-8')


def render_statements(text, stream, api):
    pieces = re.findall(r'<<\s*(' + LITERAL + r'|std::endl)', text)
    leftovers = re.sub(r'<<\s*(?:' + LITERAL + '|std::endl)', '', text)
    api.require(pieces and re.fullmatch(stream + r'\s*;', leftovers.strip()),
                'The locked generator statement has an unexpected expression')
    return ''.join('\n' if piece == 'std::endl' else json.loads(piece) for piece in pieces)


def render(wrapper_source, qt_source, have_gtk3, api):
    def statement(text, pattern):
        items = list(re.finditer(pattern, text))
        api.require(len(items) == 1, 'Expected one matching generator expression in the locked source')
        return items[0][0]

    wrapper = wrapper_source.split('std::ostringstream oss;', 1)[1]
    beginning = statement(wrapper, r'oss << "#! /usr/bin/env bash"[^;]+;')
    ending = statement(wrapper, r'oss << std::endl\s+<< "exec [^;]+;')
    hook_call = statement(wrapper, r'oss << "source [^;]+;')
    # std::filesystem::path streams its filename surrounded by quotes.
    hook_call = (hook_call.replace('APPRUN_HOOKS_DIRNAME', json.dumps('apprun-hooks'))
                 .replace('p.filename()', json.dumps(json.dumps(HOOK))))
    launch = ''.join(render_statements(piece, 'oss', api) for piece in (beginning, hook_call, ending))
    config_source, hook_source = qt_source.split('inline bool createAppRunHook', 1)
    config = render_statements(statement(config_source, r'ofs << "# generated by linuxdeploy-plugin-qt"[^;]+;'), 'ofs', api)
    hook = statement(hook_source, r'(?s)ofs << "# generated by linuxdeploy-plugin-qt".*?<< "esac" << std::endl;')
    scheme = json.dumps('gtk3' if have_gtk3 else 'gtk2')
    hook = render_statements(hook.replace('(haveGtk3 ? "gtk3" : "gtk2")', scheme), 'ofs', api)
    return dict(zip(OUTPUTS, (launch.encode(), hook.encode(), config.encode(), config.encode())))


def verify(stage, prepared, execution, lock_path, api):
    tools = stage / 'work/tools'
    archives = {key: tools / (key + '-source.tar.gz') for key in SOURCES}
    if not all(path.is_file() for path in archives.values()):
        return {}, {}
    lock = api.read_json(lock_path)['tools']
    deployed = {item['path']: item for item in prepared['deployment']['files']}
    sources = {key: source_text(path, key, lock[key], api) for key, path in archives.items()}
    for key in SOURCES:
        pin = lock[key]
        original = tools / pin['name']
        api.require(original.is_file() and not original.is_symlink() and original.stat().st_size == pin['size'] and
                    api.digest(original) == pin['sha256'], 'The linuxdeploy producer differs from the locked executable')
    calls = [entry for entry in execution['executions'] if Path(entry['arguments'][0]).name == lock['linuxdeploy']['name'] and
             '--deploy-deps-only' in entry['arguments']]
    api.require(len(calls) == 1 and calls[0]['exitCode'] == 0 and
                calls[0]['arguments'][3:5] == ['--plugin', 'qt'] and
                calls[0]['tool']['sha256'] == lock['linuxdeploy']['sha256'],
                'There is no successful original linuxdeploy invocation using the locked Qt plugin')
    observed = render(sources['linuxdeploy'], sources['linuxdeployPluginQt'],
                      'appimage/usr/plugins/platformthemes/libqgtk3.so' in deployed, api)
    files = {}
    for name, content in observed.items():
        entry = {'size': len(content), 'sha256': hashlib.sha256(content).hexdigest()}
        api.require(all(deployed.get(name, {}).get(key) == value for key, value in entry.items()),
                    'The locked linuxdeploy generators do not reproduce the actual package output: ' + name)
        files[name] = entry
    return files, archives
